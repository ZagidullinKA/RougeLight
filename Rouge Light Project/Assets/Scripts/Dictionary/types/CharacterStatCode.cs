// Перечисление CharacterStatCode определяет все возможные характеристики персонажей и мобов в игре
// Каждое значение соответствует определенному атрибуту игрового объекта
public enum CharacterStatCode
{
    // Основные характеристики здоровья
    MaxHP,             // Максимальное количество здоровья (HP)
    ActualHP,          // Текущее количество здоровья

    // Боевые характеристики
    Dmg,               // Базовый урон атаки
    AtkSpeed,          // Скорость атаки (количество атак в секунду)
    CritChance,        // Шанс нанесения критического удара (%)
    Armor,             // Количество брони (снижение получаемого урона)

    // Характеристики передвижения
    MoveSpeed,         // Скорость передвижения
    RotateSpeed,       // Скорость поворота

    // Защитные характеристики
    EvadeChance,       // Шанс уклонения от атаки (%)
    DebuffResist,      // Сопротивление негативным эффектам

    // Особые способности
    Vampire,           // Вампиризм (% урона превращается в здоровье)
    Luck,              // Удача (влияет на различные случайные события)

    // Характеристики связанные с подбором предметов
    HpFromDropRestore, // Количество восстанавливаемого HP от подбираемых предметов
    DropRadius,        // Радиус подбора предметов

    // Характеристики снарядов
    BulletFlySpeed,    // Скорость полета снарядов
    BulletTimeAlive,   // Время жизни снарядов

    // Уникальные характеристики мобов
    IdMob,             // Идентификатор моба
    DeathPrice         // Награда за убийство моба
}