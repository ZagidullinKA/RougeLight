// Перечисление TypeOfDamage определяет типы урона в игре
// Используется для идентификации источника и типа наносимого урона
public enum TypeOfDamage
{
    // Урон от периодического эффекта (Damage over Time)
    // Применяется для:
    // - Горения
    // - Отравления
    // - Кровотечения и других эффектов
    TYPE_DOT,

    // Урон от непосредственной атаки
    // Применяется для:
    // - Ближних атак
    // - Дальнобойных атак
    // - Специальных способностей
    TYPE_ATTACK
}