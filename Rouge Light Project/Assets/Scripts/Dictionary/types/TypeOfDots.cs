// Перечисление TypeOfDots определяет механику расчета урона для Damage-over-Time (DoT) эффектов
public enum TypeOfDots
{
    // Процентный урон от максимального здоровья цели
    // Формула: (MaxHP * процент) / 100 за тик
    // Пример: 5% от maxHP каждый тик
    TYPE_PERCENT,

    // Фиксированный урон за тик
    // Наносит постоянное значение урона каждый тик
    // Пример: 10 урона каждый тик
    TYPE_FIXED,

    // Процентный урон от базового урона атаки
    // Формула: (BaseDmg * процент) / 100 за тик
    // Пример: 150% от базового урона атаки каждый тик
    TYPE_BASE_DMG_PERCENT
}