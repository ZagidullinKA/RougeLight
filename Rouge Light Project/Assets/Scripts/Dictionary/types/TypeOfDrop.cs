// Перечисление TypeOfDrop определяет категории предметов, которые могут выпадать в игре
// Используется системой дропа для определения типа и поведения выпадающих предметов
public enum TypeOfDrop
{
    // Улучшение характеристик персонажа
    // Влияет на базовые параметры героя:
    // - Увеличивает здоровье, урон, скорость и др.
    // - Может давать постоянные или временные бонусы
    TYPE_CHARACTER,

    // Улучшение Damage-over-Time (DoT) эффектов
    // Усиливает или добавляет новые периодические эффекты:
    // - Увеличивает урон или длительность существующих эффектов
    // - Открывает новые типы эффектов (огонь, яд и др.)
    TYPE_DOT,

    // Игровая валюта
    // Используется для:
    // - Покупки предметов у торговцев
    // - Улучшения оборудования
    // - Разблокировки способностей
    TYPE_MONEY,

    // Восстановление здоровья
    // Мгновенно восстанавливает часть здоровья:
    // - Может быть фиксированным значением или процентом
    // - Может иметь дополнительные эффекты (регенерация)
    TYPE_HEAL
}