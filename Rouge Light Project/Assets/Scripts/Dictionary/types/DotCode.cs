// Перечисление DotCode определяет типы эффектов Damage over Time (DoT) в игре
// Каждое значение соответствует определенному типу периодического урона
public enum DotCode
{
    // Эффект горения - наносит периодический урон от огня
    // Характеристики:
    // - Постепенный урон с течением времени
    // - Может иметь визуальные эффекты пламени
    Fire,

    // Эффект отравления - наносит периодический урон ядом
    // Характеристики:
    // - Медленный, но продолжительный урон
    // - Может снижать другие характеристики
    Poison
}