// Интерфейс IDamageable определяет контракт для объектов, которые могут получать урон
// Реализуется всеми сущностями, способными принимать повреждения (персонажи, враги, разрушаемые объекты)
public interface IDamageable
{
    // Метод для расчета полученного урона с учетом защиты (брони и других модификаторов)
    // Параметры:
    // damage - базовый входящий урон
    // typeDamage - тип нанесенного урона (физический, магический и т.д.)
    void CalculateDamageAfterArmor(int damage, TypeOfDamage typeDamage);

    // Метод проверки возможности уклонения от атаки
    // Возвращает:
    // true - если уклонение успешно, false - если атака попадает
    bool TryDodge();
}